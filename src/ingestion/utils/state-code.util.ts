/**
 * Normalizes state name, region slug, or 2-letter state code into a 2-letter uppercase postal code.
 * Defaults to 'NC' for empty or unspecified inputs.
 */
export function normalizeStateCode(
  value?: string | null,
  fallback = 'NC',
): string {
  if (!value) return fallback;
  const trimmed = value.trim();
  if (!trimmed) return fallback;

  const upper = trimmed.toUpperCase();
  if (upper.length === 2) {
    return upper;
  }

  const code = US_STATE_NAME_TO_CODE[upper];
  if (code) {
    return code;
  }

  return fallback;
}
